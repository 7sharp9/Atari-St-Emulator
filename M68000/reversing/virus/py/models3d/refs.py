models=[0xaa72,0xaab8,0xab62,0xac66,0xae30,0xaee8,0xafc8,0xb01a,0xb06c,0xb0be,0xb110,0xb162,0xb1ca,0xb23e,0xb2f6,0xb348,0xb400,0xb4e0,0xb5e6,0xb756,0xb806,0xb920,0xb9d0,0xba54,0xbb88,0xbc64,0xbda4,0xbee4,0xc088,0xc2b4,0xc390,0xc472,0xc5b2,0xc6f2,0xc79c,0xc7e8,0xc834,0xc9a6,0xcb30,0xcce2,0xcd50,0xcdbe,0xce2c]
print('table 23f98:')
for i in range(64):
    print(i,'%x'%l(0x23f98+4*i),end='; ')
print()
for m in models:
    hits=[a for a in range(0xc000,0x27000,2) if l(a)==m]
    hits+= [a for a in range(0x27000,0x40000,2) if l(a)==m]
    print('%05x'%m,['%05x'%h for h in hits])
